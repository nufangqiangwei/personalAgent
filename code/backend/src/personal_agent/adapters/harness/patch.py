"""Restricted launch patch for the pinned headless CLI.

The patch is data, not a second Agent Loop: it selects the official Loop, points
the Messages transport at the loopback model proxy, mounts the permission plugin
and removes every unrelated model, tool and persistence entry. Endpoints and
tokens arrive through the per-attempt environment, so no secret is written here.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

MODEL_ID = "deepseek-flash"
GATEWAY_BASE_URL_ENV = "PERSONAL_AGENT_GATEWAY_BASE_URL"
GATEWAY_TOKEN_ENV = "PERSONAL_AGENT_GATEWAY_TOKEN"
PROFILE_PATH_ENV = "PERSONAL_AGENT_PROFILE_PATH"

# A task may set exactly these variables; anything else is refused rather than
# handed to the pinned runtime.
TASK_ENVIRONMENT_KEYS = frozenset({
    GATEWAY_BASE_URL_ENV, GATEWAY_TOKEN_ENV, PROFILE_PATH_ENV, "PERSONAL_AGENT_SCOPE_EPOCH",
})

# Entries that would add model calls, tools, persistence or self-modification.
_DISABLED = (
    "hmr", "credentials", "authorization", "deepseek-account",
    "llm-retry", "llm-deepseek-account", "llm-pi-ai",
    "session-log-deepseek", "session-persistence-jsonl", "session-query-sqlite",
    "session-projection-cache", "session-telemetry-otel", "session-title-llm",
    "compaction-basic", "goal-round-driver", "plan-mode",
    "agent-instructions", "skill", "skill-filesystem", "commands", "command-feedback",
    "subagent-spawn-in-process", "subagent-fork-in-process",
    "plugin-manager", "tool-plugin-manager", "mcp-resources",
    "tool-working-directory", "tool-bash", "tool-pwsh", "tool-jobs", "tool-fs",
    "tool-fs-search", "tool-skill", "tool-subagent-control", "tool-subagent-list-agents",
    "tool-subagent", "tool-subagent-fork", "tool-workflow", "tool-todo", "tool-goal",
    "tool-web", "tool-ask-user", "tool-present", "tool-schedule", "tool-str-replace-editor",
)

_PERSONA = (
    "You execute one bounded research step. Follow the task exactly, use only the "
    "provided tools when they are necessary, and return one JSON object that "
    "satisfies the requested schema. Never invent sources or measurements."
)


def cli_patch_text(
    *,
    policy_plugin: Path,
    model_id: str = MODEL_ID,
    max_output_tokens: int = 8192,
    tool_command: Sequence[str] | None = None,
) -> str:
    """A deterministic patch; the same inputs always produce the same bytes."""
    plugin = json.dumps(policy_plugin.resolve().as_posix())
    disabled = "".join(f"- id: {name}\n  disabled: true\n" for name in _DISABLED)
    tools = ""
    if tool_command:
        command = json.dumps(str(tool_command[0]))
        arguments = json.dumps([str(item) for item in tool_command[1:]])
        tools = (
            "    - id: personal-agent-mcp\n"
            "      name: '@deepseek-ai/dsh-mcp-client'\n"
            "      config:\n"
            "        serverName: personal_agent\n"
            "        transport: stdio\n"
            f"        command: {command}\n"
            f"        args: {arguments}\n"
            "        env:\n"
            f"          {GATEWAY_BASE_URL_ENV}: !!js process.env.{GATEWAY_BASE_URL_ENV}\n"
            f"          {GATEWAY_TOKEN_ENV}: !!js process.env.{GATEWAY_TOKEN_ENV}\n"
            "        failOnStartupError: true\n"
            "        toolCallTimeoutMs: 120000\n"
        )
    return (
        "# Generated by personal_agent.adapters.harness.patch; do not edit by hand.\n"
        "# Official Loop + loopback model gateway; no persistence, no default tools.\n"
        "- id: system-prompt\n"
        "  config:\n"
        "    personaPrefix: >-\n"
        f"      {_PERSONA}\n"
        "- id: agent-default-model\n"
        "  config:\n"
        "    provider: deepseek-official\n"
        f"    model: {model_id}\n"
        "- id: llm-deepseek\n"
        "  config:\n"
        f"    baseURL: !!js process.env.{GATEWAY_BASE_URL_ENV} + '/anthropic'\n"
        f"    apiKeyEnv: {GATEWAY_TOKEN_ENV}\n"
        "    thinking: disabled\n"
        "    reasoningEffort: off\n"
        f"    maxTokens: {max_output_tokens}\n"
        "    models:\n"
        f"      - id: {model_id}\n"
        f"        maxTokens: {max_output_tokens}\n"
        "    retryPolicy:\n"
        "      mode: normal\n"
        "      maxRetries: 0\n"
        f"{disabled}"
        "- insert:\n"
        "    - id: personal-agent-policy\n"
        f"      name: {plugin}\n"
        f"{tools}"
    )


def write_cli_patch(
    destination: Path,
    *,
    policy_plugin: Path,
    model_id: str = MODEL_ID,
    max_output_tokens: int = 8192,
    tool_command: Sequence[str] | None = None,
) -> Path:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        cli_patch_text(
            policy_plugin=policy_plugin,
            model_id=model_id,
            max_output_tokens=max_output_tokens,
            tool_command=tool_command,
        ),
        encoding="utf-8",
    )
    return destination
